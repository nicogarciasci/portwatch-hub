let CURRENT_LANG = 'pt-BR';

function setLanguage(lang) {
  CURRENT_LANG = I18N[lang] ? lang : 'pt-BR';
  document.documentElement.lang = CURRENT_LANG;
}

function currentLanguage() {
  return CURRENT_LANG;
}

function currentLocale() {
  return LOCALES[CURRENT_LANG] || 'pt-BR';
}

function monthShort(index) {
  return (MONTHS_I18N[CURRENT_LANG] || MONTHS_I18N['pt-BR'])[index] || '';
}

function languageLabel(lang) {
  const info = LANGUAGES[lang] || LANGUAGES['pt-BR'];
  return info.region ? `${info.native} (${info.region})` : info.native;
}

function t(key, vars) {
  const dict = I18N[CURRENT_LANG] || I18N['pt-BR'];
  let str = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : I18N['pt-BR'][key];
  if (str == null) str = key;
  if (vars) {
    str = str.replace(/\{(\w+)\}/g, (_match, name) => (vars[name] == null ? '' : String(vars[name])));
  }
  return str;
}

function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.title = t('app.title');
}
